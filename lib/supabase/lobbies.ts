// --- Map Lobby Functions ---
//
// Lobbies are admin-created rooms that gate access to a single map. Membership
// grants access to node content and lets lobbymates see each other's progress.

import { createClient } from "@/utils/supabase/server";
import type {
  LobbyAccessTier,
  MapLobby,
  MapLobbyWithCount,
  LobbyRosterEntry,
  LobbyPresenceEntry,
  NodeProgressStatus,
} from "@/types/lobby";

interface ProfileFields {
  full_name: string | null;
  avatar_url: string | null;
}

interface ProgressRow {
  user_id: string;
  node_id: string;
  node_title: string | null;
  status: NodeProgressStatus;
  arrived_at: string | null;
}

/**
 * Admin: create a lobby for a map. The join code is generated by Postgres.
 */
export const createLobby = async (
  mapId: string,
  name: string,
  accessTier: LobbyAccessTier = "full"
): Promise<MapLobby> => {
  const supabase = await createClient();

  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) {
    throw new Error("Must be authenticated to create a lobby");
  }

  const { data, error } = await supabase
    .from("map_lobbies")
    .insert({
      map_id: mapId,
      name,
      access_tier: accessTier,
      created_by: user.id,
    })
    .select()
    .single();

  if (error) {
    console.error("Error creating lobby:", error);
    throw new Error("Failed to create lobby");
  }

  return data as MapLobby;
};

/**
 * Admin: all lobbies for a map, with member counts.
 */
export const getLobbiesForMap = async (
  mapId: string
): Promise<MapLobbyWithCount[]> => {
  const supabase = await createClient();

  const { data, error } = await supabase
    .from("map_lobbies")
    .select("*, lobby_members(count)")
    .eq("map_id", mapId)
    .order("created_at", { ascending: false });

  if (error) {
    console.error("Error fetching lobbies:", error);
    throw new Error("Failed to load lobbies");
  }

  return (data ?? []).map((row) => {
    const { lobby_members: memberCounts, ...lobby } = row as MapLobby & {
      lobby_members: { count: number }[] | null;
    };
    return {
      ...lobby,
      member_count: memberCounts?.[0]?.count ?? 0,
    };
  });
};

/**
 * Admin: roster for one lobby, including each member's current node.
 */
export const getLobbyRoster = async (
  lobbyId: string
): Promise<LobbyRosterEntry[]> => {
  const supabase = await createClient();

  const { data: lobby, error: lobbyError } = await supabase
    .from("map_lobbies")
    .select("map_id")
    .eq("id", lobbyId)
    .single();

  if (lobbyError || !lobby) {
    console.error("Error loading lobby:", lobbyError);
    throw new Error("Failed to load lobby");
  }

  const { data: members, error: membersError } = await supabase
    .from("lobby_members")
    .select("user_id, joined_at, profiles(full_name, avatar_url)")
    .eq("lobby_id", lobbyId);

  if (membersError) {
    console.error("Error loading roster:", membersError);
    throw new Error("Failed to load roster");
  }

  const userIds = (members ?? []).map((m) => m.user_id as string);
  if (userIds.length === 0) return [];

  const progress = await fetchProgressForUsers(userIds, lobby.map_id as string);

  return (members ?? []).map((member) => {
    const profile = extractProfile(member.profiles);
    const rows = progress.filter((p) => p.user_id === member.user_id);
    const current = pickCurrentNode(rows);

    return {
      user_id: member.user_id as string,
      full_name: profile.full_name,
      avatar_url: profile.avatar_url,
      joined_at: member.joined_at as string,
      current_node_id: current?.node_id ?? null,
      current_node_title: current?.node_title ?? null,
      completed_count: rows.filter((r) => r.status === "passed").length,
    };
  });
};

/**
 * Admin: open or close a lobby. Closing blocks NEW joins only -- existing
 * members keep their access.
 */
export const setLobbyOpen = async (
  lobbyId: string,
  isOpen: boolean
): Promise<void> => {
  const supabase = await createClient();

  const { error } = await supabase
    .from("map_lobbies")
    .update({ is_open: isOpen })
    .eq("id", lobbyId);

  if (error) {
    console.error("Error updating lobby:", error);
    throw new Error("Failed to update lobby");
  }
};

